const DICTS: Record<Locale, Dict> = { en: EN, sw: SW };

export function translate(locale: Locale, key: string, params?: Record<string, string | number>): string {
  let str = DICTS[locale][key] ?? EN[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const STORAGE_KEY = 'beaver.locale';

const I18nContext = React.createContext<I18nContextValue | null>(null);

/* Locale is stored in localStorage. We read it through useSyncExternalStore so
 * the SSR/static render is always English (getServerSnapshot) while the client
 * applies the saved locale *after* hydration — this avoids the hydration
 * mismatch that otherwise breaks the (currently-breaking) language toggle on
 * statically-prerendered pages like the landing page. */
const localeListeners = new Set<() => void>();

/* In-app browsers / webviews can block localStorage (SecurityError). We fall back to an
 * in-memory store so the language toggle still works there, it just won't persist. */
let memoryLocale: Locale | null = null;

function readStoredLocale(): string | null {
  try {
    return window.localStorage.getItem(STORAGE_KEY);
  } catch {
    return null;
  }
}

function getStoredLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  const stored = memoryLocale ?? readStoredLocale();
  return stored === 'sw' || stored === 'en' ? stored : 'en';
}

function subscribeLocale(listener: () => void): () => void {
  localeListeners.add(listener);
  return () => {
    localeListeners.delete(listener);
  };
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const locale = React.useSyncExternalStore<Locale>(subscribeLocale, getStoredLocale, () => 'en');

  const setLocale = React.useCallback((l: Locale) => {
    memoryLocale = l;
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage blocked (webview) — keep in-memory locale active */
    }
    localeListeners.forEach((fn) => fn());
  }, []);

  const t = React.useCallback(
    (key: string, params?: Record<string, string | number>) => translate(locale, key, params),
    [locale],
  );

  const value = React.useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = React.useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

/* ───────────────────── Language toggle button ───────────────────── */

export function LanguageToggle() {
  const { locale, setLocale, t } = useI18n();
  const next: Locale = locale === 'en' ? 'sw' : 'en';
  const flag = locale === 'en' ? '🇬🇧' : '🇹🇿';
  return (
    <button
      type="button"
      onClick={() => setLocale(next)}
      className="tap inline-flex items-center gap-1.5 rounded-xl px-3 py-2 text-sm font-medium text-slate-500 transition-colors hover:bg-slate-100 hover:text-slate-800"
      title={t('lang.en')}
      aria-label={t('lang.en')}
    >
      <span className="text-base leading-none" aria-hidden>
        {flag}
      </span>
      <span className="hidden sm:inline">{locale === 'en' ? 'English' : 'Kiswahili'}</span>
    </button>
  );
}
